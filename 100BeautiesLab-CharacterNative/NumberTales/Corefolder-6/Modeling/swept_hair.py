def valley(angle,t,tip,root,start):
    f=np.clip((t-start)/(1-start),0,1)
    centre=tip+(root-tip)*(1-f)**1.45
    strength=np.sin(.5*pi*f)**.75
    return angle-centre,strength


def hair_map(number,path):
    from PIL import Image
    y,x=np.mgrid[:512,:1024]
    a=((x+.5)/1024*2-1)*pi
    t=1-(y+.5)/512
    base,edge={6:((255,118,162),(214,83,128)),57:((255,238,98),(209,188,65))}[number]
    amount=np.zeros_like(a)
    for tip,root,start in VALLEYS[number]:
        d,strength=valley(a,t,tip,root,start)
        # The root fades into the crown. The visible line pinches into the
        # deepest part of the sculpted fold; its shoulder keeps a soft tone.
        mask=np.exp(-(d/.017)**2)*.53+np.exp(-((d-.013)/.043)**2)*.30
        amount=np.maximum(amount,strength*mask)
    weight=amount[...,None]
    rgb=np.array(base)*(1-weight)+np.array(edge)*weight
    Image.fromarray(np.uint8(np.round(rgb))).save(path,optimize=True)
